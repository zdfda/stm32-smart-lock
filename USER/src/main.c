void mode_upoled()
{
	static uint8_t last_mode = 0xFF;
	static uint8_t a=0,b=0,c=0;
    if (key_mode!=last_mode){oled_clear();last_mode=key_mode;a=0;b=0;c=0;}
	switch(key_mode)
	{
		case 0:
			show_img();
			break;
		case 1:
			if (a==0)
			{	b=0;c=0;
                if (danger_flag>0&&((danger_flag%3)+1)!=1)
				{
					danger_flag++;     
                } 
				else if(danger_flag>0)
				{
                    danger_flag--;      
                }
                a=1;                 
            }
			show_data1();
			break;
		case 2:
			if (b==0)
			{	a=0;c=0;
                if (danger_flag>0&&((danger_flag%3)+1)!=2)
				{
					danger_flag++;     
                } 
				else if(danger_flag>0)
				{
                    danger_flag--;      
                }
                b=1;                 
            }
			show_data2();
			break;
		case 3:	
			if (c==0)
			{	a=0;b=0;
                if (danger_flag>0&&((danger_flag%3)+1)!=3)
				{
					danger_flag++;     
                } 
				else if(danger_flag>0)
				{
                    danger_flag--;      
                }
                c=1;                 
            }
			show_data3();
			break;
		case 4:
			show_time();
			break;
		case 5:
			show_data4();
			break;
		case 6:
			show_data5();
			break;
		case 7:
			show_data6();
			break;
		default:
			show_img();
	}
}
