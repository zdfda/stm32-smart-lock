typedef struct
{
    uint8_t reg;
    uint8_t val;
} paj_cmd_t;
uint8_t move_state=0;
static int paj_write_reg(uint8_t reg, uint8_t val)
{
    return iic1_write(paj7620_address,reg,&val,1);
}

static int paj_read_regs(uint8_t reg, uint8_t *buf, uint16_t len)
{
    return iic1_read(paj7620_address,reg,buf,len);
}

static void paj_select_bank(uint8_t bank)
{
    paj_write_reg(PAJ7620_REG_BANK, bank);
}

int paj7620_is_ok(void)
{
    return HAL_I2C_IsDeviceReady(&hi2c1,paj7620_address,3,100);
}

