int paj7620_init(void)
{
    uint8_t data0=0,data1=0;
    const uint32_t n=sizeof(paj_init_seq)/sizeof(paj_init_seq[0]);

    HAL_Delay(10);

    paj_select_bank(0x00);
    paj_select_bank(0x00);

    if(paj_read_regs(0x00,&data0,1)!=0)
    {
        printf("PAJ7620: read 0x00 fail\r\n");
        return -1;
    }
    if(paj_read_regs(0x01,&data1,1)!=0)
    {
        printf("PAJ7620: read 0x01 fail\r\n");
        return -1;
    }
    printf("Addr0=0x%02X, Addr1=0x%02X\r\n", data0, data1);
    if(data0!=0x20||data1!=0x76)
    {
        printf("PAJ7620: ID mismatch, expect 0x20/0x76\r\n");
        return -1;
    }

    for(uint32_t i=0;i<n;i++)
    {
        if(paj_write_reg(paj_init_seq[i].reg,paj_init_seq[i].val)!=0)
        {
            printf("PAJ7620: init fail i=%lu reg=0x%02X val=0x%02X\r\n",(unsigned long)i,paj_init_seq[i].reg,paj_init_seq[i].val);
            return -2;
        }
    }

    paj_select_bank(0x00);  

    printf("PAJ7620: init done\r\n");
    return 0;
}

int paj7620_read_raw(uint8_t *g0, uint8_t *g1)
{
    uint8_t g[2] = {0};
    if(paj_read_regs(0x43,&g[0],1)!=0)
    {
        *g0=0;*g1=0;
        return 0;
    }
    if(paj_read_regs(0x44,&g[1],1)!=0) 
    {
        *g0=0;*g1=0;
        return 0;
    }
    *g0=g[0];
    *g1=g[1];
    return(g[0]|g[1])?1:0;
}

paj_gesture_t paj7620_read_gesture(void)
{
    uint8_t g0=0,g1=0;

    if (!paj7620_read_raw(&g0,&g1))return PAJ_G_NONE;

    if (g0&0x01)return PAJ_G_RIGHT;
    if (g0&0x02)return PAJ_G_LEFT;
    if (g0&0x04)return PAJ_G_UP;
    if (g0&0x08)return PAJ_G_DOWN;
    if (g0&0x10)return PAJ_G_FORWARD;
    if (g0&0x20)return PAJ_G_BACKWARD;
    if (g0&0x40)return PAJ_G_CW;
    if (g0&0x80)return PAJ_G_CCW;
    if (g1&0x01)return PAJ_G_WAVE;
    return PAJ_G_NONE;
}
#define GES_REACTION_TIME 500
#define GES_QUIT_TIME 1000

void paj7620_demo_loop(void)
{
    uint8_t data=0,data1=0;

    iic1_read(paj7620_address,0x43,&data,1);
	move_state=data;
    switch (data) {
        case 0x01: /* RIGHT */
            HAL_Delay(GES_REACTION_TIME);
            iic1_read(paj7620_address,0x43,&data,1);
            if(data==0x02)
            {
				ctrl_sg90(180);
                //printf("Right-Left\r\n");
            }else if(data==0x10)
            {
				ctrl_sg90(90);
                //printf("Forward\r\n");
                HAL_Delay(GES_QUIT_TIME);
            }else if(data==0x20)
            {
				ctrl_sg90(90);
                //printf("Backward\r\n");
                HAL_Delay(GES_QUIT_TIME);
            }
            else
            {
				ctrl_sg90(180);
                //printf("Right\r\n");
            }
            break;

        case 0x02: /* LEFT */
            HAL_Delay(GES_REACTION_TIME);
            iic1_read(paj7620_address, 0x43, &data, 1);
            if (data==0x01)
            {
				ctrl_sg90(180);
                //printf("Left-Right\r\n");
            }
            else if(data==0x10)
            {
                //printf("Forward\r\n");
				ctrl_sg90(90);
                HAL_Delay(GES_QUIT_TIME);
            }
            else if(data==0x20)
            {
				ctrl_sg90(90);
                //printf("Backward\r\n");
                HAL_Delay(GES_QUIT_TIME);
            }
            else
            {
				ctrl_sg90(180);
                //printf("Left\r\n");
            }
            break;

		case 0x04: /* UP */
            HAL_Delay(GES_REACTION_TIME);
            iic1_read(paj7620_address,0x43,&data,1);
            if(data==0x08)
            {
				ctrl_sg90(90);
                //printf("Up-Down\r\n");
            }
            else if(data==0x10)
            {
                //printf("Forward\r\n");
				ctrl_sg90(90);
                HAL_Delay(GES_QUIT_TIME);
            }
            else if(data==0x20)
            {
				ctrl_sg90(90);
                //printf("Backward\r\n");
                HAL_Delay(GES_QUIT_TIME);
            }
            else
            {
				ctrl_sg90(90);
                //printf("Up\r\n");
            }
            break;

        case 0x08: /* DOWN */
            HAL_Delay(GES_REACTION_TIME);
            iic1_read(paj7620_address, 0x43, &data, 1);
            if(data==0x04)
            {
				ctrl_sg90(90);
                //printf("Down-Up\r\n");
            }
            else if(data==0x10)
            {
				ctrl_sg90(90);
                //printf("Forward\r\n");
                HAL_Delay(GES_QUIT_TIME);
            }else if(data==0x20)
            {
				ctrl_sg90(90);
                //printf("Backward\r\n");
                HAL_Delay(GES_QUIT_TIME);
            }
            else
            {
				ctrl_sg90(90);
                //printf("Down\r\n");
            }
            break;

        case 0x10: 
            HAL_Delay(GES_REACTION_TIME);
            iic1_read(paj7620_address,0x43,&data,1);
            if(data==0x20)
            {
                printf("Forward-Backward\r\n");
				ctrl_sg90(90);
                HAL_Delay(GES_QUIT_TIME);
            }
            else
            {
                printf("Forward\r\n");
				ctrl_sg90(90);
                HAL_Delay(GES_QUIT_TIME);
            }
            break;

        case 0x20: /* BACKWARD */
            HAL_Delay(GES_REACTION_TIME);
            iic1_read(paj7620_address,0x43,&data,1);
            if (data==0x10){
                printf("Backward-Forward\r\n");
				ctrl_sg90(90);
                HAL_Delay(GES_QUIT_TIME);
            }
            else
            {
                printf("Backward\r\n");
				ctrl_sg90(90);
                HAL_Delay(GES_QUIT_TIME);
            }
            break;

        case 0x40:
            printf("Clockwise\r\n");
            break;

        case 0x80:
            printf("anti-clockwise\r\n");
            break;

        default:
            iic1_read(paj7620_address,0x44,&data1,1);
            if(data1==0x01)
            {
                printf("wave\r\n");
            }
            break;
    }

    HAL_Delay(100);
}
